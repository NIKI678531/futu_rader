"""进程时间的唯一入口。

守卫③（`frontend/scripts/guards.mjs`）禁止业务逻辑读系统时间。理由是**口径**：
区间、时间桶、演示锚点一旦跟着墙上的钟走，同一份代码今天和明天算出两个数，
而那种红几乎无法定位 —— 它跟你改的东西毫无关系（[ADR-0012](../docs/adr/0012-frozen-demo-anchor.md)）。
这条红线一个字都不松：**口径永远不读钟**，区间与时间桶由后端下发（PRD §5），
锚点从数据里取（`meta_kv.data_max_ts`），不从系统时间取。

但标注管线有一类时间戳不属于数据口径：任务租约什么时候过期、某次 run 什么时候开始和
结束、某一行什么时候被改过，以及操作员显式选择“日历昨天”或当天请求预算时所需的运行日
（[ADR-0017](../docs/adr/0017-ai-annotation-pipeline-production.md)）。
它们记录的是**进程发生过什么**，而不是数据讲了什么。拿一个冻结的假时钟去记这些，
记下来的就是假话 —— 而这套管线的全部价值就在于「每条结论都能追溯到它真实发生的
那次运行」。租约更直接：假时钟会让租约永不过期，崩掉的 worker 领走的任务再没人能捡回来。

所以规则的准确表述不是「不许读钟」，而是**「读钟只能走这一扇门」**：

- 口径计算**永远不该**出现在本模块的调用方里；
- 调用它的地方一律是审计时间戳与租约到期判断；
- 要在测试里冻结时间，传 `now=` 参数，不 monkeypatch 全局。

一扇门和一份豁免名单的区别在于：名单会越来越长而没人删；门只有一扇，
`grep -rn "clock.now()" worker/` 就能一次列全所有读过钟的地方，并逐个问
「这是审计时间戳，还是偷偷溜进来的口径」。
"""

from datetime import datetime


def now(tz=None):
    """墙上的钟；仅供审计、租约、调度和显式选择的运行日。"""
    return datetime.now(tz)
