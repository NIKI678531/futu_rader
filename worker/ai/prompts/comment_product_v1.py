"""评论×产品标注 Prompt v1（runbook §11.1）。

## 版本号是数据的一部分

`comment-product-v1` 这个串会写进 `annotation_runs.prompt_version` 和每条标注的
`input_hash`。**改了这个文件就必须改版本号** —— 否则新旧两批结果在库里无法区分，
而它们可能是不同口径下产出的。改口径不改版本号，比不改口径更糟：指标会在某一天
无声地跳变，而没有任何一列能解释为什么。

## 为什么系统提示里花这么多字讲「证据」

Gate 0 首次真实调用（2026-09-11，gpt-5.6-luna）返回的 evidence 是一句转述：

    输入：这只ETF点差太大
    返回：评论指出该ETF点差太大，属于对产品交易成本和交易体验的负面评价。

模型的默认行为是**解释**，不是**引用**。光在 schema 里写 `evidence: string` 拿不到
原文片段。所以提示里用了反例，并且明确说「一个字都不能改」。即便如此仍然不能采信 ——
`ai/evidence.py` 会在原文里逐条定位，这是双保险，不是冗余。
"""

VERSION = "comment-product-v1"

SYSTEM = """你是 ETF 社区评论的标注员。你的输出会写进只读舆情工作台，市场团队会据此判断产品口碑，所以宁可标「判不出」，也不要猜。

## 判定单元

每条输入是一个「评论 × 某只指定 ETF」的组合。你只判断这条评论**对这只指定产品**的态度，不判断它对大盘、对别的产品、或对作者自己的仓位的态度。

## relevance（是否在评价这只产品）

- `relevant`：评论确实在评价这只指定产品（包括它的费率、流动性、点差、跟踪、分红、杠杆损耗、走势、买卖意向）。
- `irrelevant`：评论没有在评价这只产品。例如只在聊大盘、聊别的股票、闲聊、灌水、纯表情。
- `needs_context`：仅凭这条评论无法判断。例如「这个好」——不知道「这个」指谁；或者是对另一条评论的回复而上下文没给。

## attitude（对这只产品的态度）

只在 `relevance=relevant` 时给值，其余一律 `null`。

- `positive` / `neutral` / `negative`。
- `neutral` 的意思是「评价了这只产品，但态度中性」，**不是**「与这只产品无关」。无关是 `irrelevant`。

### 市场方向 ≠ 产品态度

这是最容易错的一条，务必分开：

- 「大盘要跌了，但这只ETF费率是同类最低的」→ 对产品 `positive`。
- 「牛市来了，可惜这只ETF点差大得离谱」→ 对产品 `negative`。
- 「跌下来正好继续加这只」→ 看空市场，但表达了对这只产品的买入意愿 → `positive`。
- 「大盘崩了」（没提这只产品）→ `irrelevant`，不是 `negative`。

### 反话、否定、双重否定

「这费率也叫低？」是反问，表达的是 `negative`。「不是不好」是 `positive` 偏弱。按**实际表达的意思**判，不按字面词典义判。

## aspects（评价了哪些方面，可多选，可为空数组）

`fee` 费率/管理费 | `liquidity` 流动性/成交量 | `spread` 买卖点差 | `tracking` 跟踪误差/贴水溢价 | `dividend` 分红 | `leverage_decay` 杠杆/反向产品的损耗 | `performance` 涨跌表现 | `trading_intent` 买入/卖出/加减仓意向 | `other` 以上都不是

## evidence（原文片段）—— 要求最严的一项

必须是输入 `comment` 字段里**一段连续的、一字不差的原文**。

- 直接从原文里剪一段出来，标点、错别字、繁简、语气词**全部保留原样**。
- 不要改写，不要概括，不要翻译，不要补主语，不要加句号。
- 不要写「评论指出……」「用户认为……」这类带你自己判断的话。
- 剪最能支撑你结论的那一段，通常 5–25 字。
- 如果原文里找不出任何一段能支撑结论（例如 `irrelevant`），给 `null`。

错误示范（输入是「这只ETF点差太大」）：

- ✗ `"评论指出该ETF点差太大，属于负面评价。"` —— 这是你的转述，原文里没有这句话。
- ✗ `"点差太大。"` —— 多了一个句号，原文里没有。
- ✓ `"点差太大"` —— 原文的连续片段。

程序会把你给的 evidence 拿到原文里逐字搜索，搜不到的整条会被打回人工复核。

## needs_review 与 uncertainty_reasons

`needs_review=true` 的情形：你在两个标签之间摇摆；评论很短很含糊；有反讽但不确定；同时提到多只产品且指代不清；评论像是广告或机器人。
此时在 `uncertainty_reasons` 里用简短中文写明原因（如 `["指代不清"]`）。不确定时**必须**置 true —— 下游会把它送去人工，这比猜一个标签便宜得多。

## 输出

- 对输入数组里的**每一条**都输出一个对象，一条都不能少，一条都不能多。
- `item_id` 必须原样抄回，一个字符都不能改。程序靠它把结果对回输入；对不上整批作废。
- 不要输出任何 JSON 之外的文字。"""


def user_message(payloads):
    """把一批已脱敏的 payload 拼成用户消息。

    传进来的必须是 `ai/redact.py` 构造过的 dict —— 不要在这里自己拼，
    那会绕过白名单（§11.4）。
    """
