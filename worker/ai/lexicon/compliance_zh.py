TAGS = tuple(LEXICON)


def _any(text_low, words):
    return [w for w in words if w.lower() in text_low]


def hits(text):
    """返回 `{tag: [命中词...]}`，只含命中的类。规则按 `mode`：

    - `entity_or_action`：机构词或动作词任一命中。
    - `action`：动作／指控词命中。
    - `entity_and_rumor`：事件词**且**传闻／号召词同时命中（「清盘」单独出现可能是在讨论公告）。

    这是**召回**规则，允许误报 —— 它不产生任何结论，只产生一份给人看的清单。
    """
    if not text:
        return {}
    low = text.lower()
    out = {}
    for tag, spec in LEXICON.items():
        ent = _any(low, spec["entity"])
        act = _any(low, spec["action"])
        rum = _any(low, spec["rumor"])
        mode = spec["mode"]
        if mode == "entity_or_action" and (ent or act):
            out[tag] = ent + act
        elif mode == "action" and act:
            out[tag] = act
        elif mode == "entity_and_rumor" and ent and rum:
            out[tag] = ent + rum
    return out


def labels():
    return {tag: spec["label"] for tag, spec in LEXICON.items()}
